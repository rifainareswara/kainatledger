import uuid
from datetime import date as date_type, datetime, timezone
from decimal import Decimal
from typing import TYPE_CHECKING, Optional

import sqlalchemy as sa
from sqlmodel import Field, Relationship, SQLModel

if TYPE_CHECKING:
    from app.models.category import Category
    from app.models.transfer import Transfer
    from app.models.user import User
    from app.models.wallet import Wallet


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Transaction(SQLModel, table=True):
    __tablename__ = "transactions"

    id: uuid.UUID = Field(default_factory=uuid.uuid4, primary_key=True)
    user_id: uuid.UUID = Field(foreign_key="users.id", index=True)
    wallet_id: uuid.UUID = Field(foreign_key="wallets.id", index=True)
    category_id: uuid.UUID = Field(foreign_key="categories.id", index=True)

    amount: Decimal = Field(decimal_places=2, max_digits=15)
    # Stored as plain string "income"/"expense"
    tx_type: str = Field(
        sa_column=sa.Column("type", sa.String(10), index=True, nullable=False),
    )

    tx_date: date_type = Field(
        sa_column=sa.Column("date", sa.Date(), index=True, nullable=False),
    )
    note: Optional[str] = Field(default=None, max_length=500)
    # Stored as plain string — no PG enum type
    payment_method: Optional[str] = Field(
        default=None,
        sa_column=sa.Column("payment_method", sa.String(20), nullable=True),
    )

    # Set when this transaction was generated by a transfer
    transfer_id: Optional[uuid.UUID] = Field(
        default=None, foreign_key="transfers.id", index=True
    )

    created_at: datetime = Field(default_factory=utcnow)
    updated_at: datetime = Field(default_factory=utcnow)

    # Relationships
    owner: Optional["User"] = Relationship(back_populates="transactions")
    wallet: Optional["Wallet"] = Relationship(back_populates="transactions")
    category: Optional["Category"] = Relationship(back_populates="transactions")
    transfer: Optional["Transfer"] = Relationship(back_populates="transactions")
